"""Renders the scripted simulation as a Telegram-style chat page (demo.html) for the portfolio."""
import html
import tempfile
from datetime import date
from pathlib import Path

from booking_logic import BookingFlow, BookingStore

flow = BookingFlow(BookingStore(Path(tempfile.mkdtemp()) / "b.csv"), today=date(2026, 10, 26))
msgs = [("user", "/book"), ("bot", flow.start(1))]
for m in ["Haircut", "tomorrow", "09:00", "11:00", "Alex Sample", "+44 7700 900123", "Yes"]:
    msgs += [("user", m), ("bot", flow.handle(1, m))]

parts = []
for who, content in msgs:
    if who == "user":
        parts.append(f'<div class="msg user">{html.escape(content)}</div>')
    else:
        text, opts = content
        btns = "".join(f"<span>{html.escape(o)}</span>" for o in opts)
        parts.append(f'<div class="msg bot">{html.escape(text).replace(chr(10), "<br>")}</div>'
                     + (f'<div class="kb">{btns}</div>' if opts else ""))

page = f"""<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Telegram booking bot — Demo project</title><style>
body{{margin:0;font:15px/1.45 system-ui,-apple-system,"Segoe UI",Roboto,sans-serif;background:#e7ebf0;display:flex;justify-content:center}}
.phone{{width:100%;max-width:460px;min-height:100vh;background:#8fb38f url() ;background:linear-gradient(160deg,#a8c7a0,#7fa98a);display:flex;flex-direction:column}}
.top{{background:#517da2;color:#fff;padding:.8rem 1rem;display:flex;gap:.7rem;align-items:center}}
.av{{width:38px;height:38px;border-radius:50%;background:#f4b860;display:grid;place-items:center;font-weight:700;color:#5a3a00}}
.top small{{display:block;opacity:.8}}.note{{background:#fff8d6;color:#6b5600;font-size:.8rem;text-align:center;padding:.35rem}}
.chat{{padding:1rem .8rem;display:flex;flex-direction:column;gap:.45rem}}
.msg{{max-width:80%;padding:.5rem .75rem;border-radius:12px;box-shadow:0 1px 1px rgba(0,0,0,.12)}}
.bot{{background:#fff;align-self:flex-start;border-bottom-left-radius:4px}}.user{{background:#effdde;align-self:flex-end;border-bottom-right-radius:4px}}
.kb{{display:flex;flex-wrap:wrap;gap:4px;max-width:85%}}.kb span{{background:rgba(255,255,255,.55);padding:.3rem .7rem;border-radius:8px;font-size:.85rem;color:#1f3b2a}}
</style></head><body><div class="phone"><div class="top"><div class="av">SB</div><div><b>Sample Barber Bot</b><small>bot · demo</small></div></div>
<div class="note">Demo project: transcript generated by running the real bot logic (render_chat.py). Fictional business.</div>
<div class="chat">{''.join(parts)}</div></div></body></html>"""
Path(__file__).with_name("demo.html").write_text(page, encoding="utf-8")
print("Wrote demo.html")
